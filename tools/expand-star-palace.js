/* 逐条替换 */
let applied = 0, missed = [];
Object.keys(EXPAND).forEach((key) => {
  const [star, palace] = key.split('@');
  const fields = EXPAND[key];

  // 定位到该星该宫位的块
  const starIdx = src.indexOf(`    '${star}': {`);
  if (starIdx < 0) { missed.push(key + '(星未找到)'); return; }

  // 该星块的结束位置：下一个 "    'XXX': {" 或块尾
  const nextStar = src.indexOf("\n    '", starIdx + 10);
  const blockEnd = nextStar > 0 ? nextStar : src.length;
  const block = src.slice(starIdx, blockEnd);

  const palaceRe = new RegExp(`(${palace}:\\s*\\{)([^}]*)(\\})`);
  const m = block.match(palaceRe);
  if (!m) { missed.push(key + '(宫未找到)'); return; }

  let inner = m[2];
  Object.keys(fields).forEach((f) => {
    const fieldRe = new RegExp(`${f}:\\s*'[^']*'`);
    if (fieldRe.test(inner)) {
      inner = inner.replace(fieldRe, `${f}: '${fields[f].replace(/'/g, "\\'")}'`);
    } else {
      // 该字段原本不存在，补上
      inner = inner.replace(/\s*$/, '') + `, ${f}: '${fields[f]}' `;
    }
  });

  const newBlock = block.replace(palaceRe, `$1${inner}$3`);
  src = src.slice(0, starIdx) + newBlock + src.slice(blockEnd);
  applied++;
});

fs.writeFileSync(FILE, src, 'utf8');
console.log('已更新 ' + applied + ' 处');

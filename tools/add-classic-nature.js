/* 在每颗星的 tag 后面插入 classic / src / note 字段
 * 定位方式：'星名': {\n      tag: '...',
 */
let added = 0, missed = [];
Object.keys(ADD).forEach((star) => {
  const a = ADD[star];
  // 匹配该星块的开头
  const re = new RegExp("('" + star + "':\\s*\\{\\s*\\n\\s*tag:\\s*'[^']*',)");
  const m = src.match(re);
  if (!m) { missed.push(star); return; }

  const ins = m[1] +
    "\n      // 原书星性定性（可对照《紫微斗数精成》第八章）\n" +
    "      classic: '" + a.classic.replace(/'/g, "\\'") + "',\n" +
    "      classicSrc: '" + a.src.replace(/'/g, "\\'") + "',\n" +
    "      classicNote: '" + a.note.replace(/'/g, "\\'") + "',";

  src = src.replace(re, ins);
  added++;
});

fs.writeFileSync(FILE, src, 'utf8');
console.log('已补 ' + added + ' 颗星的原书定性');
if (missed.length) console.log('未匹配: ' + missed.join(', '));
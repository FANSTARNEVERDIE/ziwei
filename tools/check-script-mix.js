/* 保留的传统写法（紫微斗数专有名词） */
const KEEP = ['紫微斗數', '命盤', '星盤'];

const FILES = ['index.html', 'js/app.js', 'js/interpret.js', 'js/star-palace.js',
  'js/export.js', 'js/store.js', 'js/leap.js', 'sw.js'];

let issues = [];

FILES.forEach((f) => {
  const p = path.join(__dirname, '..', f);
  if (!fs.existsSync(p)) return;
  const lines = fs.readFileSync(p, 'utf8').split('\n');

  lines.forEach((line, i) => {
    // 注释里的繁体不影响用户，跳过
    if (/^\s*(\/\/|\*|\/\*)/.test(line)) return;
    // HTML 注释同理
    if (/^\s*<!--/.test(line)) return;

    let probe = line;
    KEEP.forEach((k) => { probe = probe.split(k).join(''); });

    const hits = [];
    Object.keys(T2S).forEach((t) => {
      if (probe.includes(t)) hits.push(t + '→' + T2S[t]);
    });
    if (hits.length) {
      issues.push({ file: f, line: i + 1, hits, text: line.trim().slice(0, 76) });
    }
  });
});

console.log('=== 简繁混用检查 ===\n');
if (!issues.length) {
  console.log('✓ 未发现正文中的繁体字（检查 ' + FILES.length + ' 个文件）');
} else {
  console.log('发现 ' + issues.length + ' 行：\n');
  issues.forEach((r) => {
    console.log('  ' + r.file + ':' + r.line + '  [' + r.hits.join(', ') + ']');
    console.log('      ' + r.text);
  });
}
console.log('\n合计: ' + issues.length + ' 行');
process.exit(issues.length ? 1 : 0);